export interface SourceInput {
  kind: SourceKind;
  /** Personal authors as published ("Chuang K-J" or "洪珮瑜"). */
  authors?: string[];
  /** True when the research notes list only the first author(s). */
  etAl?: boolean;
  /** Corporate author, publisher or news outlet, in both languages. */
  org?: L10n;
  /** Publication year, only when the research notes give it. */
  year?: number;
  /** ISO date (yyyy-mm or yyyy-mm-dd) when known. */
  date?: string;
  title: string;
  titleIsDescriptive?: boolean;
  /** Title in the other language. */
  titleTranslated?: string;
  /**
   * A short name for the document (ours, in the reader's language), at most 16 Chinese characters
   * or 40 English letters, for the source chips on /electric/ where the full headline is too long.
   * It names the document only: no figure the title does not carry, no claim.
   */
  shortTitle?: Partial<L10n>;
  /** The translated title is the publisher's own (otherwise it is ours). */
  titleTranslationOfficial?: boolean;
  /** Journal or series name. */
  container?: string;
  volume?: string;
  issue?: string;
  pages?: string;
  reportNumber?: string;
  isbn?: string;
  doi?: string;
  url?: string;
  accessed: string;
  language: Locale;
  readLevel: ReadLevel;
  /** Internal note for editors (English): how it was read, quirks, limits. */
  readNote?: string;
  /** A note readers see under the citation (a second-hand source, for example). */
  readerNote?: L10n;
}

